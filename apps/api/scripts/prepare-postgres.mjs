import { readFile, writeFile } from 'node:fs/promises'

// One model source for local SQLite and deployed PostgreSQL. Never edit the
// generated schema; migrations are reviewed and committed separately.
const source = new URL('../prisma/schema.prisma', import.meta.url)
const target = new URL('../prisma/schema.postgresql.prisma', import.meta.url)
const schema = await readFile(source, 'utf8')
if (!schema.includes('provider = "sqlite"')) {
  throw new Error('Expected the canonical SQLite datasource in schema.prisma')
}
await writeFile(target, '// Generated by scripts/prepare-postgres.mjs\n' +
  schema.replace('provider = "sqlite"', 'provider = "postgresql"'))
